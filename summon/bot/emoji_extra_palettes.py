def _parse_palette(source: str, expected_count: int) -> tuple[tuple[str, str], ...]:
    """Validate ordered 1-based entries and keep their IDs as opaque strings."""
    result: list[tuple[str, str]] = []
    for index, line in enumerate(source.strip().splitlines(), 1):
        match = re.fullmatch(r"([0-9]+)\)(\S+) \[([0-9]{19})\]", line.strip())
        if not match or int(match.group(1)) != index:
            raise ValueError(f"Invalid user-provided emoji palette entry {index}")
        result.append((match.group(2), match.group(3)))
    if len(result) != expected_count:
        raise ValueError("Unexpected user-provided emoji palette size")
    return tuple(result)


