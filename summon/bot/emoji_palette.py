# This lookup also covers unused palette entries when they are later used as
# button icons. It never treats a custom emoji ID as a JavaScript number.
PALETTE_FALLBACKS: Final[Mapping[str, str]] = MappingProxyType(
    {identifier: glyph for icons in PALETTES.values() for glyph, identifier in icons}
)


def palette_icon(palette: str, number: int) -> tuple[str, str]:
    """Select an item using the 1-based numbering in the user's original list."""
    icons = PALETTES[palette]
    if number < 1 or number > len(icons):
        raise IndexError("Emoji palette number is out of range")
    return icons[number - 1]


def vector_icon(number: int) -> tuple[str, str]:
    """Select an item from the original Emoji Vector Icons list."""
    return palette_icon("vector", number)
